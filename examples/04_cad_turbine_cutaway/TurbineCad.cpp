// Showcase 04 (CAD / engineering): axial-centrifugal turbine assembly on the CAD studio cyclorama.
//
//   * 20 assetgen parts: intake bell-mouth, compressor and turbine casing shells, three hex-bolt
//     rings, shaft + spinner, three axial rotor stages, two stator rings (magenta bands + steel
//     vanes), gold centrifugal impeller (main vanes + splitters), volute scroll, bearing housing,
//     nozzle guide vanes, turbine wheel, exhaust cone, support cradle.
//   * Exploded view: every part slides along the shaft axis by its own spread x the slider.
//   * Ghosted casing: Render::MaterialDesc::opacity (blended pass, silhouette-boosted, no shadow),
//     optional casing wireframe overlay (profile rings + generatrix lines), screen-space CAD ink
//     edges (entity-id / depth discontinuities) seen through the ghost.
//   * Rotor speed: rotors, impeller, shaft and turbine wheel spin about the axis.
